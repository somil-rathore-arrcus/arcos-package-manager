"""Generate debian/upstream.md from a verified resolution.

The file records two facts and nothing else:

    Upstream Source: <the upstream repository>

    Current Upstream Branch: <the upstream branch the ARCoS fork tracks>

Everything else the tool knows - the evidence, the release reference, the raw
commit counts, the backlog - belongs in the pull request body, where a reviewer
reads it once, not in a file the package carries forever. The plan carries only
the status, the reason and the review flags beside the two values; the full body
can be read before anything is pushed in a push-only dry run's links file.

One source of truth: the file is rendered from the same UpstreamResolution the
dashboard shows, so the committed record and the tool can never disagree.

Nothing is guessed. A value that was not established says so, in a fixed N/A
sentence that names what is missing, and the reasons a reviewer should look
twice are returned as review flags rather than written into the file.

Generation is deterministic - the same resolution renders byte-identical output,
with no timestamps or local paths - because the file is compared against what is
already in the repository to decide whether anything needs to change at all.

Nothing here writes to a repository. It reports CREATED, UPDATED, NO_CHANGE or
CONFLICT and hands the content back; committing is a separate, explicit act.
"""

from __future__ import annotations

import difflib
import logging
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional

from ..domain.enums import RefStrategy, ResolutionStatus, UpstreamMdOutcome
from ..domain.models import (
    UpstreamMdDocument, UpstreamMdReviewFlag, UpstreamResolution,
)

log = logging.getLogger(__name__)

UPSTREAM_MD_PATH = "debian/upstream.md"


def review_dir(out_dir, release: str) -> Path:
    """Where a release's reviewed files live: out/upstream-md-<release>/
    <package>/debian/upstream.md. One folder per release, so regenerating one
    release never replaces the files another release's plan was reviewed on."""
    return Path(out_dir) / f"upstream-md-{release}"
NONE = "N/A"

SOURCE_LABEL = "Upstream Source"
BRANCH_LABEL = "Current Upstream Branch"

# The branch field when no branch was established. Fixed text, so the plan, the
# verifier and a reader can all tell "not known" from a value at a glance.
NO_BRANCH = f"{NONE} - no upstream branch verified"

# Files written by older versions of this tool carried this marker. They are
# still ours to update, so it is still recognised; nothing writes it any more.
MARKER = "Generated by the ARCoS Package Manager"

# Review flags. None of them blocks publishing: each says what a reviewer has to
# check, and they are shown in the plan, the generator's output, the publisher's
# dry run and the pull request body.
BRANCH_NOT_VERIFIED = "BRANCH_NOT_VERIFIED"
TAG_ONLY = "TAG_ONLY"
BRANCH_FROM_TAG = "BRANCH_FROM_TAG"
BASE_TAG_NOT_IN_FORK = "BASE_TAG_NOT_IN_FORK"
FALLBACK_REF = "FALLBACK_REF"
MAPPING_WARNINGS = "MAPPING_WARNINGS"

# Lakshya's own spelling puts a space before the colon; both are the same field.
_FIELD = re.compile(
    rf"^({re.escape(SOURCE_LABEL)}|{re.escape(BRANCH_LABEL)})\s*:\s*(.*?)\s*$"
)


@dataclass(frozen=True)
class BranchField:
    """The "Current Upstream Branch" value, and what it rests on.

    `verified` is True only when the value is a branch recorded evidence names:
    the branch the mapping recorded, or - for a tag-only mapping - the upstream
    default branch, or the branch config/overrides.yaml names, that the ancestry
    probe measured as holding the fork's base. Then
    `tag` keeps the tag it was derived from and `basis` says what the probe
    measured. A tag is a fixed point, not something the fork can track, so it is
    never itself written as a branch; with no such measurement a tag-only
    mapping is written as N/A with the tag named.
    """

    value: str
    branch: Optional[str] = None
    tag: Optional[str] = None
    verified: bool = False
    basis: Optional[str] = None


@dataclass(frozen=True)
class ReviewFlag:
    code: str
    detail: str


def _unverified(resolution: UpstreamResolution) -> str:
    return f"{NONE} - not verified (status {resolution.status.value})"


def _clean(value) -> str:
    """One line, no stray whitespace.

    Refs and URLs cannot contain whitespace, so this changes nothing real; it
    keeps a damaged mapping cell from turning the two-line file into something
    parse_fields would reject.
    """
    return " ".join(str(value or "").split())


def source_field(resolution: UpstreamResolution) -> str:
    """The "Upstream Source" value.

    Only a VERIFIED resolution names a repository. An unverified one has at most
    a candidate, and a candidate written into the package would read as fact.
    """
    if resolution.status is not ResolutionStatus.VERIFIED:
        return _unverified(resolution)
    upstream = resolution.upstream_repository
    url = _clean(upstream.url if upstream else "")
    return url or NONE


def branch_field(resolution: UpstreamResolution) -> BranchField:
    """The "Current Upstream Branch" value, from recorded facts only.

    The order is the order of evidence: the branch the mapping recorded, then a
    tag (named, but not a branch), then the ref selection's own ls-remote kind,
    and only then a ref nobody recorded the kind of - which is reported, not
    assumed to be a branch.
    """
    if resolution.status is not ResolutionStatus.VERIFIED:
        return BranchField(value=_unverified(resolution))

    branch = _clean(resolution.upstream_branch)
    if branch:
        return BranchField(value=branch, branch=branch, verified=True)

    selection = resolution.ref_selection
    tag = _clean(resolution.upstream_tag)
    if not tag and selection is not None and selection.kind == "tag":
        tag = _clean(selection.ref)
    if tag:
        held = _branch_holding_base(resolution, tag)
        if held is not None:
            ref, basis = held
            return BranchField(value=ref, branch=ref, tag=tag, verified=True,
                               basis=basis)
        value = f"{NO_BRANCH}; upstream tag {tag}"
        if (selection is not None and selection.arcos_contains_base is False
                and _clean(selection.base_tag) == tag):
            value += " (the ARCoS fork does not contain this tag)"
        return BranchField(value=value, tag=tag)

    if selection is not None and selection.kind == "branch" and _clean(selection.ref):
        # The selection's kind came from the same ls-remote that proved the ref
        # exists, so it is recorded evidence even where the split fields are not
        # (a row from a mapping written before they existed).
        ref = _clean(selection.ref)
        return BranchField(value=ref, branch=ref, verified=True)

    ref = _clean(resolution.upstream_ref)
    if ref:
        return BranchField(
            value=f"{NO_BRANCH}; ref {ref} is not recorded as a branch or a tag"
        )
    return BranchField(value=NO_BRANCH)


def _branch_holding_base(resolution: UpstreamResolution, tag: str):
    """The upstream branch a tag-only fork follows, as (branch, basis), or None.

    The ancestry probe measures the repository's default branch - and the
    branch config/overrides.yaml names, which is recorded instead when it is
    the same ref - against the same ARCoS commit as the tag, and every
    measurement is kept as a candidate. When such a branch shares history with
    the fork and the fork has no more commits outside it than outside the tag,
    the branch holds all of the fork's upstream history the tag accounts for,
    and usually more: the fork sits on that line, often past the release Debian
    ships. A fork taken from a side branch has commits the branch lacks, so it
    has more outside the branch than outside its tag and does not qualify;
    neither does a branch the probe did not measure. Of two that qualify, the
    one with fewer commits outside it wins, then the one a person named.
    """
    upstream = resolution.upstream_repository
    url = _clean(upstream.url if upstream else "")
    if not url:
        return None
    measured = [c for c in resolution.candidates
                if _clean(c.repository) == url and c.shares_history
                and c.arcos_only is not None]
    tagged = next((c for c in measured
                   if c.kind == "tag" and _clean(c.ref) == tag), None)
    if tagged is None:
        return None
    branches = [c for c in measured
                if c.strategy in _BRANCH_ROLES and c.kind == "branch"
                and _clean(c.ref) not in ("", "HEAD")
                and c.arcos_only <= tagged.arcos_only]
    if not branches:
        return None
    branch = min(branches, key=lambda c: (c.arcos_only,
                                          c.strategy is not RefStrategy.CURATED))
    ref = _clean(branch.ref)
    return ref, (
        f"the ancestry probe measured {ref}, {_BRANCH_ROLES[branch.strategy]}, "
        f"against the same ARCoS commit: it shares history, and the fork has "
        f"{branch.arcos_only} commit(s) outside {ref} against "
        f"{tagged.arcos_only} outside {tag}"
    )


# The branches a tag-only file may name instead of N/A, and how each is described.
_BRANCH_ROLES = {
    RefStrategy.DEFAULT_BRANCH: "the upstream default branch",
    RefStrategy.CURATED: "the branch config/overrides.yaml names",
}


def review_flags(resolution: UpstreamResolution) -> List[ReviewFlag]:
    """What a reviewer should check before this file is merged, in fixed order."""
    field = branch_field(resolution)
    selection = resolution.ref_selection
    flags: List[ReviewFlag] = []

    if not field.verified:
        if resolution.status is not ResolutionStatus.VERIFIED:
            why = (f"the mapping is {resolution.status.value}, not VERIFIED, so "
                   f"no upstream branch is recorded")
        elif field.tag:
            why = (f"the mapping records upstream tag {field.tag}, not a branch; "
                   f"which upstream branch the fork follows has not been verified")
        elif _clean(resolution.upstream_ref):
            why = (f"the mapping records ref {_clean(resolution.upstream_ref)} "
                   f"but not whether it is a branch or a tag")
        else:
            why = "the mapping records no upstream ref"
        flags.append(ReviewFlag(BRANCH_NOT_VERIFIED, why))

    if field.tag and field.basis:
        detail = (f"the mapping selected upstream tag {field.tag}, not a branch; "
                  f"{field.branch} is written because {field.basis}")
        if selection is not None and selection.reason:
            detail += f"; {_clean(selection.reason)}"
        flags.append(ReviewFlag(BRANCH_FROM_TAG, detail))
    elif field.tag:
        detail = f"upstream tag {field.tag} is the only ref recorded"
        if selection is not None and selection.reason:
            detail += f"; {_clean(selection.reason)}"
        flags.append(ReviewFlag(TAG_ONLY, detail))

    if selection is not None and selection.arcos_contains_base is False:
        flags.append(ReviewFlag(
            BASE_TAG_NOT_IN_FORK,
            f"the ARCoS fork does not contain upstream tag "
            f"{_clean(selection.base_tag) or NONE} (Debian upstream version "
            f"{_clean(selection.debian_upstream_version) or NONE})",
        ))

    if selection is not None and selection.is_fallback:
        flags.append(ReviewFlag(
            FALLBACK_REF,
            _clean(selection.reason)
            or f"{_clean(selection.ref)} was chosen as a fallback",
        ))

    warnings = [_clean(w) for w in resolution.warnings if _clean(w)]
    if warnings:
        flags.append(ReviewFlag(MAPPING_WARNINGS, "; ".join(warnings)))
    return flags


def parse_fields(text: Optional[str]) -> Optional[Dict[str, str]]:
    """The two fields of a file in this format, or None if it is anything else.

    Strict on purpose: a file with any other line in it may hold something this
    tool does not know about, and replacing it is a decision for a person.
    """
    if text is None:
        return None
    found: Dict[str, str] = {}
    for line in re.sub(r"\r\n?", "\n", text).split("\n"):
        if not line.strip():
            continue
        match = _FIELD.match(line)
        if match is None or match.group(1) in found:
            return None
        found[match.group(1)] = match.group(2)
    if set(found) != {SOURCE_LABEL, BRANCH_LABEL}:
        return None
    return found


class UpstreamMdService:
    def render(self, resolution: UpstreamResolution) -> str:
        """The file: the two fields, a blank line between them, nothing else.

        The blank line is what makes GitHub render them as two lines rather
        than run them together into one paragraph.
        """
        return (
            f"{SOURCE_LABEL}: {source_field(resolution)}\n\n"
            f"{BRANCH_LABEL}: {branch_field(resolution).value}\n"
        )

    def generate(self, resolution: UpstreamResolution,
                 existing: Optional[str] = None) -> UpstreamMdDocument:
        """Render the file and say what writing it would do."""
        if resolution.status is ResolutionStatus.NO_UPSTREAM:
            raise ValueError(
                f"{resolution.package} has no upstream, so there is nothing to "
                f"record in {UPSTREAM_MD_PATH}."
            )

        content = self.render(resolution)
        document = UpstreamMdDocument(
            package=resolution.package,
            debian_release=resolution.debian_release,
            path=UPSTREAM_MD_PATH,
            content=content,
            existing_content=existing,
            review_flags=[
                UpstreamMdReviewFlag(code=f.code, detail=f.detail)
                for f in review_flags(resolution)
            ],
        )

        document.outcome, diff = classify(existing, content)
        if document.outcome in (UpstreamMdOutcome.UPDATED,
                                UpstreamMdOutcome.CONFLICT):
            document.diff = diff
        return document


def classify(existing: Optional[str], content: str):
    """What writing `content` over `existing` would do, and the diff.

    Shared by generation and publishing, so the plan and the commit cannot reach
    different conclusions about the same file. `existing` is None when there is
    no file.
    """
    if existing is None:
        return UpstreamMdOutcome.CREATED, _diff("", content)
    if _normalise(existing) == _normalise(content):
        return UpstreamMdOutcome.NO_CHANGE, ""
    # Ours to replace: a file from an older version of this tool, or a file
    # already in this two-field format - which holds nothing the new one would
    # lose, so the diff shows the whole change. Anything else may carry
    # information this tool does not know about, and replacing it is a decision
    # for a person.
    ours = MARKER in existing or parse_fields(existing) is not None
    outcome = UpstreamMdOutcome.UPDATED if ours else UpstreamMdOutcome.CONFLICT
    return outcome, _diff(existing, content)


def _normalise(text: str) -> str:
    """Compare on content, not on trailing whitespace or line endings."""
    return "\n".join(
        line.rstrip() for line in re.sub(r"\r\n?", "\n", text or "").split("\n")
    ).strip()


def _diff(existing: str, generated: str) -> str:
    return "".join(
        difflib.unified_diff(
            (existing or "").splitlines(keepends=True),
            (generated or "").splitlines(keepends=True),
            fromfile=f"a/{UPSTREAM_MD_PATH}", tofile=f"b/{UPSTREAM_MD_PATH}",
        )
    )
